// —— Bold blocky rendering: each glyph column is doubled one pixel right (5×7 → 6×7), all caps ——
const gl = ch => G[ch] || G[ch.toUpperCase()] || G['?'];
let BOLD = 0; export const setBold = b => { BOLD = b ? 1 : 0; };
const bw = ch => gl(ch)[0].length + BOLD;
// Parse "*word*" spans → [{s, hi}]
export function spans(str) {
  const out = []; let hi = false, cur = '';
  for (const ch of str) { if (ch === '*') { if (cur) out.push({ s: cur, hi }); cur = ''; hi = !hi; } else cur += ch; }
  if (cur) out.push({ s: cur, hi }); return out;
}
export const plain = s => s.replace(/\*/g, '');
export function textW(s, sc = 1) { let w = 0; for (const ch of plain(s).toUpperCase()) w += (bw(ch) + 1) * sc; return Math.max(0, w - sc); }

// Mask pass: calls put(x, y) for every lit native pixel of the string at scale sc
function glyphs(s, x0, y0, sc, put) {
  let x = x0;
  for (const ch of s.toUpperCase()) {
    const g = gl(ch);
    for (let y = 0; y < g.length; y++) for (let b = 0; b < g[y].length; b++) if (g[y][b] === '#')
      for (let k = 0; k <= BOLD; k++) for (let j = 0; j < sc; j++) for (let i = 0; i < sc; i++) put(x + (b + k) * sc + i, y0 + y * sc + j);
    x += (bw(ch) + 1) * sc;
  }
  return x;
}
// Draw a line with *highlight* markup. pal = {fg, hi, ink}. Ink: outline left/top + shadow down-right (sc ≥ 2), shadow only at 1×.
export function line(fb, str, x0, y0, sc, pal) {
  const sp = spans(str), seq = [];
  let x = x0; for (const p of sp) { seq.push({ ...p, x }); x += textW(p.s, sc) + sc; }
  const sh = Math.max(1, Math.round(sc / 2));
  for (const p of seq) glyphs(p.s, p.x, y0, sc, (X, Y) => {
    for (let d = 1; d <= sh + 1; d++) fb.px(X + 1, Y + d, pal.ink);
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) fb.px(X + dx, Y + dy, pal.ink);
  });
  for (const p of seq) glyphs(p.s, p.x, y0, sc, (X, Y) => fb.px(X, Y, p.hi ? pal.hi : pal.fg));
}
// Centred line
export function lineC(fb, str, cx, y0, sc, pal) { line(fb, str, Math.round(cx - textW(str, sc) / 2), y0, sc, pal); }
// Yellow 3-tone number for the counter: body / lower half shade / outline
export function bigNum(fb, str, cx, y0, sc, P) {
  const x0 = Math.round(cx - textW(str, sc) / 2), h = 7 * sc;
  glyphs(str, x0, y0, sc, (X, Y) => { for (let d = 1; d <= sc; d++) fb.px(X + d, Y + d, P.ink); for (const [dx, dy] of [[-1,0],[1,0],[0,-1],[0,1]]) fb.px(X + dx, Y + dy, P.ink); });
  glyphs(str, x0, y0, sc, (X, Y) => fb.px(X, Y, (Y - y0) > h * .62 ? P.shade : (Y - y0) < sc ? P.light : P.body));
}
