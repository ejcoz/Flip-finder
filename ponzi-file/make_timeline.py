"""voice/dur.json + voice/words.json → timeline.js. Every cue is anchored to a spoken word."""
import os, json
HERE = os.path.dirname(os.path.abspath(__file__))
D = json.load(open(os.path.join(HERE, 'voice', 'dur.json')))
W = json.load(open(os.path.join(HERE, 'voice', 'words.json')))
START, GAP, BEAT = .45, .25, .55          # sentence gap; one short beat after "He wasn't."
V = {}; t = START
for k in ['l1', 'l2', 'l3', 'l4', 'l5', 'l6']:
    V[k] = round(t, 3); t += D[k] + (BEAT if k == 'l3' else GAP)
def w(line, word, which=1, n=1):           # start (1) or end (2) of the n-th occurrence of a word
    hits = [x for x in W[line] if x[0].strip('.,').lower() == word.lower()]
    return round(V[line] + max(0.0, hits[n - 1][which]), 3)
end = lambda k: round(V[k] + D[k], 3)
T = {
  'open': 2.9,                                  # hook readable 0–2.9 s, then the file opens
  't50': w('l1', '50'), 't45': w('l1', '45'),
  'exC': round(V['l2'] - .12, 3), 'name': w('l2', 'Ponzi'), 'coupon': w('l2', 'international'),
  'fake': round(end('l3') + .04, 3),            # in the beat after "He wasn't."
  'chain': round(w('l4', 'money') - .15, 3),   # chain 1: "…with money from new ones,"
  'crowd': round(w('l4', 'and') - .1, 3),       # "and the crowds kept coming."
  'chain2': round(V['l5'] - .12, 3),            # back to the chain, bigger: the reporters' math
  'need': w('l5', 'reporters'),
  'snap': round(end('l5') + .02, 3),            # in the gap after "to cover it."
  'clips': round(V['l6'] - .02, 3),
  'closed': w('l6', 'August'),                 # stamped on "August" (the score accents it; no effect over speech)
  'nameHead': w('l6', 'and'),
  'end': round(end('l6') + .1, 3),
}
TIER = [round(T['chain'] + .12, 3), w('l4', 'from'), w('l4', 'new'), w('l4', 'ones'),
        round(T['crowd'] + .6, 3), round(T['crowd'] + 1.2, 3), w('l5', 'checked'), w('l5', 'there')]
CLIPS = [round(T['clips'] + .04 + i * .2, 3) for i in range(4)]
GAPS = []                                      # silent windows between spoken lines (for sound effects)
ks = list(V)
GAPS.append([0, V['l1']])
for a, b in zip(ks, ks[1:]): GAPS.append([end(a), V[b]])
js = (f"// generated by make_timeline.py — do not edit by hand\n"
      f"export const VOICE = {json.dumps(V)};\nexport const T = {json.dumps(T, indent=1)};\n"
      f"export const TIER_T = {json.dumps(TIER)};\nexport const CLIP_T = {json.dumps(CLIPS)};\nexport const GAPS = {json.dumps(GAPS)};\n")
open(os.path.join(HERE, 'timeline.js'), 'w').write(js)
print(js)
